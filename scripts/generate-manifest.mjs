// Regenerates content/manifest.ts from the lesson files.
// Run with: npm run content:manifest
import { readdir, writeFile } from "node:fs/promises";

import { expandLessonQuestions } from "../content/questions.ts";
import { partCount } from "../content/lesson-parts.ts";

const contentDirectory = new URL("../content/", import.meta.url);

const files = (await readdir(contentDirectory))
  .filter((file) => /^lesson-\d+\.ts$/.test(file))
  .sort((a, b) => Number(a.match(/\d+/)[0]) - Number(b.match(/\d+/)[0]));

const summaries = await Promise.all(
  files.map(async (file) => {
    const loaded = await import(new URL(file, contentDirectory).href);
    const lesson = expandLessonQuestions(Object.values(loaded)[0]);
    return {
      id: lesson.id,
      arabicTitle: lesson.arabicTitle,
      title: lesson.title,
      description: lesson.description,
      tags: lesson.tags,
      questionCount: lesson.questions.length,
      partCount: partCount(lesson),
    };
  }),
);

const entries = summaries
  .map(
    (summary) =>
      `  {\n` +
      `    id: ${summary.id},\n` +
      `    arabicTitle: ${JSON.stringify(summary.arabicTitle)},\n` +
      `    title: ${JSON.stringify(summary.title)},\n` +
      `    description: ${JSON.stringify(summary.description)},\n` +
      `    tags: [${summary.tags.map((tag) => JSON.stringify(tag)).join(", ")}],\n` +
      `    questionCount: ${summary.questionCount},\n` +
      `    partCount: ${summary.partCount},\n` +
      `  },`,
  )
  .join("\n");

const source = `// Generated by scripts/generate-manifest.mjs — do not edit by hand.
// Run \`npm run content:manifest\` after changing a lesson.
//
// The home screen needs every lesson's card but not a single word of any of
// them, so the summaries ship in the entry chunk and the lessons themselves
// load on demand.

export type LessonSummary = {
  id: number;
  arabicTitle: string;
  title: string;
  description: string;
  tags: string[];
  questionCount: number;
  /** 2 for a lesson long enough to be taught in halves, otherwise 1. */
  partCount: number;
};

export const lessonSummaries: LessonSummary[] = [
${entries}
];
`;

await writeFile(new URL("manifest.ts", contentDirectory), source);
console.log(`manifest.ts: ${summaries.length} уроков`);
