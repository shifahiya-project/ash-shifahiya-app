// Rebuilds content/podcasts/catalog.ts from YouTube.
// Run with: YOUTUBE_API_KEY=… npm run podcasts:import [@handle …]
//
// The site is static files, so there is no server that could fetch the episode
// list at request time. The list is therefore pulled here, at build time, and
// committed — which also means the app opens with episodes ready and asks the
// learner for nothing. Extra handles given on the command line are imported on
// top of the ones in content/podcasts/channels.ts, without being added to it:
// the default sources are a decision, not a cache.
import { writeFile } from "node:fs/promises";

import { DEFAULT_HANDLES } from "../content/podcasts/channels.ts";
import { parseChannelHandle } from "../app/podcast-catalog.ts";
import { fetchCatalog } from "../app/podcast-youtube.ts";

const apiKey = process.env.YOUTUBE_API_KEY ?? "";
if (!apiKey) {
  console.error(
    "Нужен ключ YouTube Data API v3:\n" +
      "  YOUTUBE_API_KEY=… npm run podcasts:import\n\n" +
      "Ключ берётся в Google Cloud Console: создать проект, включить\n" +
      "«YouTube Data API v3», выпустить API key. Ключ только читает публичные\n" +
      "данные — доступа к вашему аккаунту YouTube он не даёт.",
  );
  process.exit(1);
}

const extra = process.argv.slice(2).map(parseChannelHandle).filter(Boolean);
const handles = [...new Set([...DEFAULT_HANDLES, ...extra])];

console.log(`Каналов на импорт: ${handles.length}`);
const { catalog, missing } = await fetchCatalog(handles, apiKey, (message) => console.log(`  ${message}`));

for (const handle of missing) {
  console.warn(`  ! ${handle} не найден — канал переименован или удалён`);
}
if (catalog.channels.length === 0) {
  console.error("Ни один канал не открылся — каталог не тронут.");
  process.exit(1);
}

const channelLines = catalog.channels
  .map(
    (channel) =>
      `    {\n` +
      `      id: ${JSON.stringify(channel.id)},\n` +
      `      handle: ${JSON.stringify(channel.handle)},\n` +
      `      title: ${JSON.stringify(channel.title)},\n` +
      `      uploadsPlaylistId: ${JSON.stringify(channel.uploadsPlaylistId)},\n` +
      `    },`,
  )
  .join("\n");

// One line per episode: the file is read by people checking what the app will
// offer, and a four-line object each would make a thousand-line diff of a
// routine refresh.
const videoLines = catalog.videos
  .map(
    (video) =>
      `    { id: ${JSON.stringify(video.id)}, channelId: ${JSON.stringify(video.channelId)},` +
      ` seconds: ${video.seconds}, publishedAt: ${JSON.stringify(video.publishedAt)},` +
      ` title: ${JSON.stringify(video.title)} },`,
  )
  .join("\n");

const source = `// Generated by scripts/import-podcasts.mjs — do not edit by hand.
// Run \`npm run podcasts:import\` with a YOUTUBE_API_KEY to refresh it.
//
// The episode list ships with the site so that the app works the moment it is
// opened, with no key and no network call of its own. It is a snapshot: new
// episodes appear here when the importer is run again, and until then the app
// offers what was known at build time. A learner who wants the list to refresh
// itself can put their own API key into the app's settings, and the device then
// keeps its own newer copy.
import type { PodcastCatalog } from "../../app/podcast-catalog.ts";

export const shippedCatalog: PodcastCatalog = {
  generatedAt: ${JSON.stringify(catalog.generatedAt)},
  channels: [
${channelLines}
  ],
  videos: [
${videoLines}
  ],
};
`;

await writeFile(new URL("../content/podcasts/catalog.ts", import.meta.url), source);

const minutes = Math.round(catalog.videos.reduce((sum, video) => sum + video.seconds, 0) / 60);
console.log(
  `catalog.ts: ${catalog.channels.length} каналов, ${catalog.videos.length} выпусков, ${minutes} мин`,
);
