// The complete source-linked edition has its own importer: its 159 lessons
// replace the previous segmentation instead of appending another book to it.
import { mkdir, readdir, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { numberName } from "./text-course-import.mjs";

export const PART4_SOURCE_REVISION = "2026-11-17";
export const PART4_CONTENT_REVISION = "tuhfat-2026-11-17";
const BOOK = "Тухфат аль-фукаха";
const KINDS = new Set([
  "verb", "noun", "masdar", "adjective", "expression", "term", "proper_name", "particle", "adverb",
]);
const RUSSIAN_ONLY_HEADINGS = new Map([
  ["h-139-2", "Первый раздел: «Твоё дело в твоих руках»"],
  ["h-139-30", "Второй раздел: слова «выбирай»"],
  ["h-140-0", "Третий раздел: слова «ты разведена, если пожелаешь»"],
  ["h-140-7", "Четвёртый раздел: слова «разведи себя сама»"],
]);
const requireSource = (condition, message) => {
  if (!condition) throw new Error(`Invalid part4 source: ${message}`);
};
const canonical = (value, location) => {
  requireSource(typeof value === "string", `${location} must be a string`);
  return value.normalize("NFC").trim();
};
const arabic = (value, location, allowEmpty = false) => {
  const text = canonical(value, location);
  requireSource((allowEmpty && text === "") || /[ء-ي]/u.test(text), `${location} has no Arabic`);
  requireSource(!/[А-Яа-яЁё\u2066-\u2069]/u.test(text), `${location} still contains an unprepared inline hint`);
  return text;
};
const russian = (value, location) => {
  const text = canonical(value, location);
  requireSource(/[А-Яа-яЁё]/u.test(text), `${location} has no Russian`);
  return text;
};
const quote = JSON.stringify;
const fileName = (id) => `lesson-${String(id).padStart(3, "0")}.ts`;

function renderLesson(lesson) {
  return `// Generated by scripts/import-part4.mjs — do not edit by hand.
import type { TextCourseLesson } from "../types";

export const part4Lesson${numberName(lesson.id)}: TextCourseLesson = {
  id: ${lesson.id},
  revision: ${quote(lesson.revision)},
  book: ${quote(lesson.book)},
  section: ${quote(lesson.section)},
  arabicTitle: ${quote(lesson.arabicTitle)},
  title: ${quote(lesson.title)},
  words: [
${lesson.words.map((word) => `    ${quote(word)},`).join("\n")}
  ],
  fragments: [
${lesson.fragments.map((fragment) => `    ${quote(fragment)},`).join("\n")}
  ],
};
`;
}

/** Validate both prepared exports and build every output before any disk write. */
export function buildPart4Revision({ glossary, reading, reviewAddresses }) {
  requireSource(glossary?.revision === PART4_SOURCE_REVISION && reading?.revision === PART4_SOURCE_REVISION,
    "both exports must be the 2026-11-17 revision");
  requireSource(glossary.format_version === 2, "expected glossary format_version 2");
  requireSource(canonical(glossary.title_ru, "glossary title") === BOOK &&
    canonical(reading.title_ru, "reading title") === BOOK, "unexpected book title");
  requireSource(Array.isArray(glossary.lessons) && glossary.lessons.length === 159 &&
    Array.isArray(reading.lessons) && reading.lessons.length === 159, "all 159 lessons are required");
  requireSource(Array.isArray(reading.items), "reading items are required");
  requireSource(reviewAddresses?.revision === PART4_CONTENT_REVISION &&
    reviewAddresses.addresses && typeof reviewAddresses.addresses === "object", "wrong review address revision");

  const rows = new Map();
  const byLesson = new Map();
  let pairs = 0;
  let headings = 0;
  let russianOnly = 0;
  for (const row of reading.items) {
    const { lesson, type, source } = row;
    requireSource(Number.isInteger(lesson) && lesson >= 1 && lesson <= 159, "row has an invalid lesson");
    requireSource(type === "pair" || type === "heading", `unknown row type ${type}`);
    requireSource(source?.kind === type && Number.isInteger(source.block), `invalid row source ${row.id}`);
    const list = byLesson.get(lesson) ?? [];
    requireSource(source.block === list.length, `nonsequential blocks in lesson ${lesson}`);
    requireSource(!rows.has(row.id), `duplicate reading ID ${row.id}`);
    const expectedId = type === "pair" ? `p-${source.id}` : `h-${lesson}-${source.block}`;
    requireSource(row.id === expectedId && (type !== "pair" || Number.isInteger(source.id)),
      `invalid reading ID ${row.id}`);
    const ar = arabic(row.ar, `row ${row.id}`, type === "heading");
    const ru = russian(row.ru, `row ${row.id}`);
    if (!ar) {
      requireSource(RUSSIAN_ONLY_HEADINGS.get(row.id) === ru, `unreviewed Russian-only heading ${row.id}`);
      russianOnly += 1;
    }
    const fragment = { arabic: ar, russian: ru, sourceId: row.id };
    if (type === "heading") {
      requireSource(source.id === null && [1, 2, 3].includes(source.level), `invalid heading ${row.id}`);
      fragment.heading = true;
      fragment.headingLevel = source.level;
      headings += 1;
    } else pairs += 1;
    rows.set(row.id, { ...row, ar, ru });
    list.push(fragment);
    byLesson.set(lesson, list);
  }
  requireSource(pairs === 4485 && headings === 183 && russianOnly === 4, "wrong reading row totals");

  const seenEntries = new Set();
  const seenContexts = new Set();
  const seenAddresses = new Set();
  const books = [];
  let globalNumber = 0;
  let teakFixes = 0;
  const lessons = glossary.lessons.map((entry, offset) => {
    const id = offset + 1;
    const header = reading.lessons[offset];
    requireSource(entry.number === id && header.number === id, `nonsequential lesson ${id}`);
    const title = russian(entry.title_ru, `lesson ${id} title`);
    requireSource(title === canonical(header.ru, `lesson ${id} reading title`), `lesson ${id} title mismatch`);
    const arabicTitle = arabic(entry.title_ar, `lesson ${id} Arabic title`, true);
    requireSource(arabicTitle === canonical(header.ar, `lesson ${id} reading Arabic title`),
      `lesson ${id} Arabic title mismatch`);
    const section = russian(entry.chapter, `lesson ${id} section`);
    requireSource(section === canonical(header.chapter, `lesson ${id} reading section`) &&
      entry.book === header.book && Number.isInteger(entry.book), `lesson ${id} book mismatch`);
    if (books.at(-1) !== entry.book) books.push(entry.book);
    requireSource(entry.previous_number === header.previous, `lesson ${id} previous number mismatch`);
    requireSource(Array.isArray(entry.entries) && Array.isArray(entry.contexts), `lesson ${id} has no glossary arrays`);
    const contexts = new Map();
    for (const context of entry.contexts) {
      requireSource(!seenContexts.has(context.id), `duplicate context ${context.id}`);
      seenContexts.add(context.id);
      const row = rows.get(context.id);
      requireSource(row?.lesson === id && row.type === context.kind && row.source.id === context.source_id,
        `context ${context.id} source mismatch`);
      requireSource(canonical(context.arabic, `context ${context.id} Arabic`) === row.ar &&
        canonical(context.russian, `context ${context.id} Russian`) === row.ru, `context ${context.id} text mismatch`);
      requireSource(Array.isArray(context.entry_ids) && context.entry_ids.length > 0 &&
        new Set(context.entry_ids).size === context.entry_ids.length, `context ${context.id} has invalid word references`);
      contexts.set(context.id, context);
    }
    const words = entry.entries.map((word, index) => {
      requireSource(typeof word.id === "string" && !seenEntries.has(word.id), `duplicate or absent word ID ${word.id}`);
      seenEntries.add(word.id);
      requireSource(word.lesson === id && word.number === index + 1 && word.global_number === ++globalNumber,
        `word ${word.id} numbering mismatch`);
      requireSource(KINDS.has(word.type), `unknown word kind ${word.type}`);
      const context = contexts.get(word.context_key);
      requireSource(context?.entry_ids.includes(word.id) && context.kind === word.source_kind,
        `word ${word.id} context mismatch`);
      requireSource(word.source?.id === word.id && word.source.contextId === context.id &&
        word.source.contextKind === context.kind && word.source.contextSourceId === context.source_id,
        `word ${word.id} provenance mismatch`);
      let ar = arabic(word.arabic, `word ${word.id}`);
      if (word.id === "tfq-vocab-0661") {
        requireSource(id === 104 && word.context_key === "p-6464" &&
          (ar === "ساج" || ar === "سَاجٌ".normalize("NFC")), "teak vocalisation fix requires review");
        ar = "سَاجٌ".normalize("NFC");
        teakFixes += 1;
      }
      const address = reviewAddresses.addresses[word.id];
      requireSource(Number.isInteger(address?.lessonId) && address.lessonId >= 1 && address.lessonId <= 159 &&
        Number.isInteger(address.index) && address.index >= 0, `word ${word.id} has no valid review address`);
      const addressKey = `${address.lessonId}:${address.index}`;
      requireSource(!seenAddresses.has(addressKey), `duplicate review address ${addressKey}`);
      seenAddresses.add(addressKey);
      return { arabic: ar, russian: russian(word.russian, `word ${word.id} translation`), kind: word.type,
        reviewLessonId: address.lessonId, reviewIndex: address.index, source: { ...word.source } };
    });
    const entryById = new Map(entry.entries.map((word) => [word.id, word]));
    for (const context of contexts.values()) {
      for (const wordId of context.entry_ids) {
        requireSource(entryById.get(wordId)?.context_key === context.id,
          `context ${context.id} has a dangling word reference ${wordId}`);
      }
    }
    const fragments = byLesson.get(id);
    requireSource(fragments?.length > 0, `lesson ${id} has no reading`);
    return { id, revision: PART4_CONTENT_REVISION, book: BOOK, section, arabicTitle, title, words, fragments };
  });
  requireSource(books.length === 9 && books.every((book, index) => book === index + 1), "expected nine sequential books");
  requireSource(seenEntries.size === 907 && seenContexts.size === 737 && teakFixes === 1,
    "wrong glossary totals or absent guarded vocalisation fix");
  requireSource(Object.keys(reviewAddresses.addresses).length === 907 &&
    Object.keys(reviewAddresses.addresses).every((id) => seenEntries.has(id)), "review address map has unexpected entries");

  const summaries = lessons.map(({ id, book, section, arabicTitle, title, words, fragments }) =>
    ({ id, book, section, arabicTitle, title, wordCount: words.length, fragmentCount: fragments.length }));
  const allWords = lessons.flatMap((lesson) => lesson.words.map((word) => ({ lesson: lesson.id, ...word })));
  const files = new Map(lessons.map((lesson) => [fileName(lesson.id), renderLesson(lesson)]));
  files.set("manifest.ts", `// Generated by scripts/import-part4.mjs — do not edit by hand.
import type { TextCourseSummary } from "../types";

export const part4Summaries: TextCourseSummary[] = ${JSON.stringify(summaries, null, 2)};
`);
  files.set("glossary.ts", `// Generated by scripts/import-part4.mjs — do not edit by hand.
import type { TextCourseWord } from "../types";

export type Part4GlossaryEntry = TextCourseWord & { lesson: number };

export const part4Glossary: Part4GlossaryEntry[] = [
${allWords.map((word) => `  ${quote(word)},`).join("\n")}
];
`);
  const reviewLessons = Object.fromEntries(allWords.map((word) =>
    [`${word.reviewLessonId}-${word.reviewIndex}`, word.lesson]));
  files.set("review-map.ts", `// Generated by scripts/import-part4.mjs — do not edit by hand.
// Retired review addresses are deliberately absent.
export const part4ReviewLessons: Record<string, number> = ${JSON.stringify(reviewLessons, null, 2)};
`);
  return { lessons, summaries, allWords, files,
    totals: { lessons: 159, words: allWords.length, contexts: seenContexts.size,
      pairs, headings, fragments: reading.items.length, russianOnlyHeadings: russianOnly } };
}

/** Replace only generated course files; helper and migration metadata stay intact. */
export async function importPart4Revision({ directory, ...source }) {
  const built = buildPart4Revision(source);
  // All 162 output strings exist and have passed source checks at this point.
  await mkdir(directory, { recursive: true });
  const existing = await readdir(directory);
  for (const [name, content] of built.files) await writeFile(join(directory, name), content, "utf8");
  for (const name of existing) {
    const match = name.match(/^lesson-(\d+)\.ts$/u);
    if (match && Number(match[1]) > built.totals.lessons) await rm(join(directory, name));
  }
  return built;
}
